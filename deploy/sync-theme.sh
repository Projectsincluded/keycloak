#!/bin/sh
# sync-theme.sh — mirror the authoritative theme source into this repository.
#
# THE THEME IS EDITED IN ONE PLACE ONLY:
#   /home/ruben/Documents/2. Ruben Flinterman/kubernetes-update-by-agentic-ai/keycloakify-starter/
#
# `deploy/theme/` in this repo is a MIRROR of that directory, produced by this script. Editing it
# here is how the two copies silently drift apart: the Dockerfile builds what is committed, while you
# keep looking at your local `yarn dev` in the original. Run this before every commit that touches
# the theme, and commit the result.
#
# The Docker build itself does NOT reach outside this repo — CI has no access to the workstation —
# which is exactly why a copy has to exist here.
#
#   ./deploy/sync-theme.sh "/path/to/keycloakify-starter"
#
# `--delete` is deliberate: a file removed from the source must disappear here too, or the image
# keeps shipping it forever.
set -eu

SRC=${1:?usage: deploy/sync-theme.sh /path/to/keycloakify-starter}
DST=$(CDPATH= cd -- "$(dirname -- "$0")/theme" && pwd)

if [ ! -f "$SRC/package.json" ]; then
    echo "error: $SRC does not look like a keycloakify project (no package.json)" >&2
    exit 1
fi

# Guard against the classic mistake of syncing the mirror onto itself.
if [ "$(CDPATH= cd -- "$SRC" && pwd)" = "$DST" ]; then
    echo "error: source and destination are the same directory ($DST)" >&2
    exit 1
fi

# Generated / machine-local things are never committed. `public/keycloakify-dev-resources` is
# regenerated by keycloakify when `yarn dev` runs, so committing it would add ~4.3 MB of noise.
rsync -a --delete \
    --exclude 'node_modules' \
    --exclude 'dist' \
    --exclude 'dist_keycloak' \
    --exclude '.git' \
    --exclude '.github' \
    --exclude '.keycloakify' \
    --exclude 'public/keycloakify-dev-resources' \
    "$SRC"/ "$DST"/

echo "synced: $SRC"
echo "     -> $DST"
echo
echo "review and commit:"
echo "  git -C \"$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)\" status --short deploy/theme"
